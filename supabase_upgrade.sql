-- Gigi's Food House - upgrade for a Supabase database that was created with
-- an earlier supabase_schema.sql. Keeps all existing accounts, orders and
-- menu items. Safe to run more than once.
--
-- Paste into Supabase Dashboard > SQL Editor and run it.

CREATE TABLE IF NOT EXISTS product_images (
  image_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mime_type  varchar(20) NOT NULL CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  data       bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  session_hash char(64) PRIMARY KEY,
  user_id      integer REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
  csrf         char(64) NOT NULL,
  expires_at   timestamptz NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions (expires_at);

-- The view ran with its owner's rights, which let the public REST API read
-- every order through it.
ALTER VIEW v_order_summary SET (security_invoker = true);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_verifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE pending_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE pending_account_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE product_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;

