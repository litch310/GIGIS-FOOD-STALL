DROP VIEW IF EXISTS v_order_summary CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS auth_attempts CASCADE;
DROP TABLE IF EXISTS pending_account_tokens CASCADE;
DROP TABLE IF EXISTS pending_accounts CASCADE;
DROP TABLE IF EXISTS account_tokens CASCADE;
DROP TABLE IF EXISTS account_verifications CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
  user_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     varchar(100) NOT NULL,
  email         varchar(150) NOT NULL UNIQUE,
  phone         varchar(20),
  password_hash varchar(255) NOT NULL,
  role          varchar(20) NOT NULL DEFAULT 'customer'
                CHECK (role IN ('owner', 'vendor', 'customer')),
  status        varchar(20) NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'pending', 'suspended')),
  created_at    timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_users_role ON users (role);

CREATE TABLE account_verifications (
  user_id      integer PRIMARY KEY REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
  verified_at  timestamptz
);

CREATE TABLE account_tokens (
  token_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
  purpose     varchar(20) NOT NULL CHECK (purpose IN ('verify', 'reset')),
  token_hash  char(64) NOT NULL UNIQUE,
  expires_at  timestamptz NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_account_tokens_user_purpose ON account_tokens (user_id, purpose);
CREATE INDEX idx_account_tokens_expiry ON account_tokens (expires_at);

CREATE TABLE pending_accounts (
  pending_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     varchar(100) NOT NULL,
  email         varchar(150) NOT NULL UNIQUE,
  phone         varchar(20),
  password_hash varchar(255) NOT NULL,
  role          varchar(20) NOT NULL CHECK (role IN ('owner', 'vendor', 'customer')),
  status        varchar(20) NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'pending', 'suspended')),
  expires_at    timestamptz NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_pending_accounts_expiry ON pending_accounts (expires_at);

CREATE TABLE pending_account_tokens (
  token_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pending_id integer NOT NULL REFERENCES pending_accounts (pending_id) ON UPDATE CASCADE ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_pending_account_tokens_pending ON pending_account_tokens (pending_id);
CREATE INDEX idx_pending_account_tokens_expiry ON pending_account_tokens (expires_at);

CREATE TABLE auth_attempts (
  attempt_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     varchar(30) NOT NULL,
  ip_address varchar(45) NOT NULL,
  email      varchar(150) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_auth_attempts_ip ON auth_attempts (action, ip_address, created_at);
CREATE INDEX idx_auth_attempts_email ON auth_attempts (action, email, created_at);
CREATE INDEX idx_auth_attempts_created ON auth_attempts (created_at);

CREATE TABLE categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        varchar(60) NOT NULL UNIQUE,
  sort_order  smallint NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);

CREATE TABLE products (
  product_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  integer NOT NULL REFERENCES categories (category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  name         varchar(100) NOT NULL UNIQUE,
  description  varchar(255),
  unit         varchar(30) NOT NULL DEFAULT '1 serving',
  price        numeric(8,2) NOT NULL CHECK (price >= 0),
  image        varchar(255),
  is_available smallint NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1)),
  is_archived  smallint NOT NULL DEFAULT 0 CHECK (is_archived IN (0, 1)),
  created_by   integer REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  updated_by   integer REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_products_category ON products (category_id);

CREATE TABLE orders (
  order_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  order_type  varchar(20) NOT NULL DEFAULT 'dine-in'
              CHECK (order_type IN ('dine-in', 'take-out', 'delivery')),
  status      varchar(20) NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending', 'preparing', 'ready', 'completed', 'cancelled')),
  notes       varchar(255),
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created ON orders (created_at);

CREATE TABLE order_items (
  order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      integer NOT NULL REFERENCES orders (order_id) ON UPDATE CASCADE ON DELETE CASCADE,
  product_id    integer NOT NULL REFERENCES products (product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  quantity      smallint NOT NULL CHECK (quantity > 0),
  unit_price    numeric(8,2) NOT NULL CHECK (unit_price >= 0),
  UNIQUE (order_id, product_id)
);
CREATE INDEX idx_order_items_product ON order_items (product_id);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TRIGGER products_updated_at
BEFORE UPDATE ON products
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER orders_updated_at
BEFORE UPDATE ON orders
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE VIEW v_order_summary AS
SELECT
  o.order_id,
  o.customer_id,
  u.full_name AS customer_name,
  u.phone AS customer_phone,
  o.order_type,
  o.status,
  o.notes,
  o.created_at,
  COALESCE(SUM(oi.quantity), 0) AS item_count,
  COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS total_amount
FROM orders o
JOIN users u ON u.user_id = o.customer_id
LEFT JOIN order_items oi ON oi.order_id = o.order_id
GROUP BY o.order_id, o.customer_id, u.full_name, u.phone,
         o.order_type, o.status, o.notes, o.created_at;

